import assert from 'node:assert/strict';
import { taskStatus, setTaskTreeStatus, recalcTaskStatus, taskListCompletion } from '../src/task-status';
import { readTaskMetadataSuffix } from '../src/task-metadata';
import { resolveTaskAppearance, sanitizeTaskStyles } from '../src/task-presentation';
import { parse, serialize, generateEmptyWeeklyMarkdown } from '../src/parser';
import { insertTableTodo } from '../src/table-model';
import { archiveCompleted, serializeTasksForNote } from '../src/task-tree';
import { scanFileTasks } from '../src/alltasks-scan';
import { unfinishedTasks } from '../src/weekly-history';
import { SyncEngine } from '../src/sync';
import { DEFAULT_SETTINGS, type TaskItem } from '../src/types';
import * as cryptoFormat from '../src/secure/format.mjs';

Object.assign(globalThis, { window: globalThis });
const open: TaskItem = { text: 'open', checked: false };
const completed: TaskItem = { text: 'done', checked: true };
const cancelled = setTaskTreeStatus(open, 'cancelled');
assert.equal(taskStatus(cancelled), 'cancelled');
assert.equal(cancelled.checked, false, 'cancelled is never completed');
assert.equal(taskListCompletion([open, cancelled]), 0);
assert.equal(taskListCompletion([completed, cancelled]), 1);
assert.equal(taskListCompletion([cancelled]), 0);
assert.equal(taskListCompletion([{ ...open, children: [completed, cancelled] }]), 1);
assert.equal(taskStatus(recalcTaskStatus({ ...open, children: [cancelled] })), 'cancelled');
assert.equal(taskStatus(recalcTaskStatus({ ...cancelled, children: [open] })), 'pending');
const tree = { ...open, children: [completed, open, cancelled] };
assert.equal(taskStatus(setTaskTreeStatus(tree, 'cancelled').children[0]!), 'completed', 'cancelling keeps prior completed children');
assert.equal(taskStatus(setTaskTreeStatus(tree, 'completed').children[2]!), 'cancelled', 'completing does not revive cancelled children');
assert.equal(taskStatus(setTaskTreeStatus(tree, 'deferred').children[1]!), 'pending', 'deferring does not change children');
assert.equal(archiveCompleted([cancelled, completed]).remaining[0], cancelled);
assert.match(serializeTasksForNote([cancelled]), /- \[-\] open/);
assert.equal(resolveTaskAppearance(cancelled, sanitizeTaskStyles(undefined)).source, 'cancelled');
assert.equal(resolveTaskAppearance(cancelled, sanitizeTaskStyles(undefined)).pendingAccent, undefined);
assert.deepEqual(readTaskMetadataSuffix('text <!--apex-task-status:deferred--> <!--apex-task-type:temporary-->'),
    { text: 'text', taskType: 'temporary', taskStatus: 'deferred' });

async function main() {
    const data = parse(generateEmptyWeeklyMarkdown());
    let table = data.columns.find(column => column.sectionType === 'table')!;
    table = insertTableTodo(table, 2, 4, 'a', 'A');
    table = insertTableTodo(table, 2, 5, 'b', 'B');
    table.cards[0]!.tasks = [{ text: '合成状态任务', checked: false, taskType: 'temporary', reminder: '2026-10-20 10:30',
        dailyNote: '日记/合成.md', collapsed: true, children: [{ ...completed }, { ...open }] }];
    data.columns = [table];
    const engine = new SyncEngine({} as any, DEFAULT_SETTINGS);
    let disk = '', writes = 0;
    const save = async (next: typeof data) => { disk = serialize(next); writes++; };
    engine.initMemory(data, save);
    const tasks = (id: string) => engine.getData()!.columns[0]!.cards.find(card => card.id === id)!.tasks;
    await engine.moveTaskToCard('a', [0], 'b', [0], 'before', true);
    const previousWrites = writes;
    await engine.setTaskStatus('b', [0], 'deferred');
    assert.equal(writes, previousWrites + 1);
    assert.equal(taskStatus(tasks('a')[0]!), 'deferred', 'linked status synchronizes in one write');
    assert.equal(tasks('a')[0]!.reminder, '2026-10-20 10:30', 'defer does not change reminder');
    engine.initMemory(parse(disk), save);
    assert.equal(taskStatus(tasks('b')[0]!), 'deferred');
    assert.equal(tasks('b')[0]!.taskType, 'temporary');
    const scan = () => scanFileTasks({ path: 'synthetic.md', stat: { mtime: 0, ctime: 0 } } as any, disk);
    assert.equal(scan()[0]!.text, '合成状态任务');
    assert.equal(scan()[0]!.taskStatus, 'deferred');
    assert.ok(unfinishedTasks(disk).some(task => task.text === '合成状态任务'));
    await engine.setTaskStatus('a', [0], 'cancelled');
    assert.equal(taskStatus(tasks('b')[0]!), 'cancelled');
    assert.equal(taskStatus(tasks('b')[0]!.children![0]!), 'completed');
    assert.equal(taskStatus(tasks('b')[0]!.children![1]!), 'cancelled');
    assert.match(disk, /- \[-\] 合成状态任务/);
    assert.ok(unfinishedTasks(disk).some(task => task.text === '合成状态任务'), 'history retains cancelled tasks');
    assert.ok(scan().every(task => task.checked), 'cancelled tasks disappear from calendar scans');
    const password = 'Synthetic-status-only';
    const recipient = await cryptoFormat.createRecipient(password);
    const envelope = await cryptoFormat.createPublic(disk, 'Synthetic task status', recipient);
    const root = await cryptoFormat.resolveRoot(password, envelope);
    const decrypted = await cryptoFormat.openAll(envelope, root);
    engine.initMemory(parse(decrypted.markdown), save);
    assert.equal(taskStatus(tasks('a')[0]!), 'cancelled', 'status survives encryption');
    await engine.setTaskStatus('b', [0, 1], 'pending');
    assert.equal(taskStatus(tasks('a')[0]!), 'pending', 'reopening child reopens both linked parents');
    assert.equal(taskStatus(tasks('b')[0]!), 'pending');
    await engine.setTaskStatus('a', [0, 1], 'deferred');
    await engine.setTaskStatus('b', [0], 'completed');
    assert.equal(taskStatus(tasks('a')[0]!), 'completed');
    assert.equal(tasks('a')[0]!.children![1]!.taskStatus, undefined, 'completion clears deferred metadata');
    await engine.setTaskStatus('a', [0], 'pending');
    assert.equal(taskStatus(tasks('b')[0]!), 'pending');
    assert.ok(!disk.includes('apex-task-status:'));
    await engine.unlinkTask('b', [0]);
    await engine.setTaskStatus('b', [0], 'cancelled');
    assert.equal(taskStatus(tasks('a')[0]!), 'pending', 'unlinked status is independent');
    engine.clearMemory();
    console.log('task status: transitions, progress, metadata, linked trees, reopen, scan/archive and encrypted round-trip passed');
}
void main().catch(error => { console.error(error); process.exitCode = 1; });
