import assert from 'node:assert/strict';
import { parse, serialize } from '../src/parser';
import { addWeeklyHistory, stampWeeklyDate, resolveWeek, historyCutoff, unfinishedTasks } from '../src/weekly-history';
import * as cryptoFormat from '../src/secure/format.mjs';
const source='---\ndashboard: true\ncustom: keep\ncolumns:\n  - name: 周计划表\n    type: table\n---\n## 周计划表\n| 类型 | 周一 | 周二 |\n| --- | --- | --- |\n| 学习 | - [ ] old<br>- [x] done | ^ |\n### A\n- [ ] parent <!--apex-sync:g:a-->\n  - [ ] child <!--apex-daily:diary.md--> <!--apex-sync:c:ca-->\n- [x] completed\n### B\n- [ ] parent <!--apex-sync:g:b-->\n  - [ ] child <!--apex-sync:c:cb-->\n';
async function main(){
 const added=addWeeklyHistory(source);
 assert.equal(addWeeklyHistory(added),added,'idempotent migration');
 assert.ok(added.endsWith('\n\n## 历史未完成计划\n'));
 assert.ok(added.includes(source.slice(source.indexOf('## 周计划表'))),'original body untouched');
 assert.ok(added.includes('custom: keep'));
 assert.ok(parse(serialize(parse(added))).columns.some(c=>c.dataviewConfig?.openSource === 'workspace'),'preset survives normal saves');
 const dated=stampWeeklyDate(added,'第3周-10月11号',new Date(2026,9,10));
 assert.equal(parse(dated).weekStart,'2026-10-11');
 assert.equal(parse(serialize(parse(dated))).weekStart,'2026-10-11','weekStart survives editing');
 assert.equal(historyCutoff(dated,'',0,new Date(2026,9,10)),'2026-10-04','future board never includes present week');
 assert.equal(historyCutoff(stampWeeklyDate(source,'2026-09-27',new Date(2026,9,10)),'',0,new Date(2026,9,10)),'2026-09-27','viewing old board excludes later weeks');
 assert.equal(resolveWeek('', '第2周-12月28号',+new Date(2026,0,2)).date,'2025-12-28','legacy dates cross year');
 assert.equal(resolveWeek('', 'undated',+new Date()).date,undefined);
 assert.equal(resolveWeek('---\nweekStart: 2026-02-31\n---','第1周-1月1号',+new Date()).date,undefined,'invalid explicit date is not guessed');
 const tasks=unfinishedTasks(dated);
 assert.deepEqual(tasks.map(t=>t.text),['parent','child','old']);
 assert.deepEqual(tasks.map(t=>t.copies),[2,2,1]);
 assert.ok(!tasks.some(t=>t.text.includes('apex-')),'internal metadata hidden');
 const other=dated+'\n## another\n### C\n- [ ] separate <!--apex-sync:g:c-->\n';
 assert.equal(unfinishedTasks(other).filter(t=>t.text==='separate').length,1,'dedup limited to one section');
 const recipient=await cryptoFormat.createRecipient('synthetic-history-password');
 const encrypted=await cryptoFormat.createPublic(source,'Template',recipient,parse(source).columns);
 const root=await cryptoFormat.resolveRoot('synthetic-history-password',encrypted);
 const opened=await cryptoFormat.openAll(encrypted,root);
 const markdown=addWeeklyHistory(opened.markdown);
 const next=await cryptoFormat.createWithRoot(markdown,opened.title,root,encrypted.domain,parse(markdown).columns,[],encrypted.id,encrypted.access);
 assert.equal((await cryptoFormat.openAll(next,root)).markdown,markdown);
 assert.equal(next.id,encrypted.id);
 assert.deepEqual(next.access,encrypted.access,'same recipient/password retained');
 assert.ok(!JSON.stringify(next).includes('历史未完成计划'),'encrypted template never contains plaintext');
 console.log('weekly history: date boundaries, legacy tasks, dedup, metadata, idempotent template and encryption passed');
}
void main().catch(e=>{console.error(e);process.exitCode=1;});
