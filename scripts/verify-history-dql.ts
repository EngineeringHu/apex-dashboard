import assert from 'node:assert/strict';
import { parseDate } from '../src/dql/functions';
import { buildPages, invalidatePath } from '../src/dql/page-builder';
import { executeDql } from '../src/dql';
import { WEEKLY_HISTORY_QUERY, weeklyHistoryConfig } from '../src/weekly-history-config';
import { addWeeklyHistory, resolveWeek } from '../src/weekly-history';
import { parse, serialize } from '../src/parser';
import { scanFileTasks } from '../src/alltasks-scan';
import { fixture } from './history-dql-fixture';
import type { ResultRow } from '../src/dql/types';
async function main(){
 assert.equal(parseDate('2026-10-11'),new Date(2026,9,11).getTime(),'date-only uses local midnight');
 assert.equal(parseDate('2026-10-11T00:00:00Z'),Date.UTC(2026,9,11),'explicit timezone is preserved');
 assert.equal(parseDate('2026-02-30'),null,'invalid calendar date is rejected');
 const f=fixture();f.files.forEach(file=>invalidatePath(file.path));
 const pages=await buildPages(f.app,{excludePaths:[f.template.path],excludeFolders:['周记/_临时解密']});
 const currentPage=pages.find(p=>p.file===f.current)!;
 const query=(dql:string,dedup=true)=>{const result=executeDql(dql,pages,{currentPage,deduplicateLinkedTasks:dedup});assert.ok(result.ok&&!result.empty,JSON.stringify(result));return result.result;};
 const flatten=(rows:readonly ResultRow[]):ResultRow[]=>rows.flatMap(row=>row.rows?flatten(row.rows):[row]);
 const result=query(WEEKLY_HISTORY_QUERY);
 assert.equal(result.rows.length,2);
 const tasks=flatten(result.rows).map(r=>r.task!);
 assert.deepEqual(tasks.map(t=>t.text),['Alpha','Legacy','Earlier']);
 assert.equal(tasks[0]!.copies,2);
 assert.equal(flatten(query(WEEKLY_HISTORY_QUERY,false).rows).length,4,'dedup is configurable');
 assert.deepEqual(query('TASK FROM "周记" WHERE completed').rows.map(r=>r.task?.text),['Done'],'editable WHERE changes result');
 assert.equal(query('TASK FROM "周记" WHERE !completed SORT text DESC LIMIT 1').rows[0]?.task?.text,'Legacy','SORT and LIMIT respected');
 assert.ok(query('TABLE this.file.path AS Source, this.weekStart AS Week FROM "周记" LIMIT 1').rows[0]!.values.includes(f.current.path),'this is querying board, not source row');
 assert.equal(query('TASK FROM "周记" WHERE syncId = "g"').rows.length,1,'shared task fields queryable');
 assert.equal(query('TASK FROM "周记" WHERE dailyNote = "diary.md"').rows.length,1);
 const custom={...weeklyHistoryConfig(),query:'TASK WHERE completed',viewMode:'list' as const};
 const raw='---\ndashboard: true\ncolumns:\n - name: History\n   type: dataview\n   dataview:\n     weeklyHistory: true\n     query: ""\n---\n## History\n';
 const upgraded=addWeeklyHistory(raw);
 assert.ok(!upgraded.includes('weeklyHistory: true'));
 assert.equal(parse(upgraded).columns[0]?.dataviewConfig?.query,WEEKLY_HISTORY_QUERY);
 const data=parse(upgraded);data.columns[0]!.dataviewConfig=custom;
 assert.equal(parse(serialize(data)).columns[0]!.dataviewConfig?.query,custom.query);
 assert.equal(parse(serialize(data)).columns[0]!.dataviewConfig?.viewMode,'list');
 assert.equal(addWeeklyHistory(serialize(data)),serialize(data),'upgrade never resets custom query');
 assert.equal(resolveWeek('','2026年第2周-10月4号',0).date,'2026-10-04','explicit year independent of ctime');
 assert.equal(scanFileTasks(f.history,'~~~\n- [ ] example\n~~~\n- [ ] real').length,1,'skip fenced examples');
 const source=pages.find(p=>p.file===f.history)!;
 const fileTasks=source.fields['file.tasks'] as any[];
 const copies=fileTasks.filter(t=>t.entries.syncId==='g').map((t,i)=>({...t,entries:{...t.entries,card:i?'B':'A'}}));
 const scoped=executeDql('TASK WHERE card = "B"',[{...source,fields:{...source.fields,'file.tasks':copies}}],{deduplicateLinkedTasks:true});
 assert.ok(scoped.ok&&!scoped.empty&&scoped.result.rows.length===1,'filter matching instance before dedup');
 // A second board for the same Sunday must see the first board's unfinished tasks.
 const peer=Object.assign(Object.create(Object.getPrototypeOf(f.current)),f.current,{path:'周记/__peer.md',name:'__peer.md',basename:'__peer'});
 f.files.push(peer);f.data.set(peer.path,f.data.get(f.current.path)!.replace('- [ ] Current','- [ ] Peer\n- [x] Peer done'));
 const sameWeekPages=await buildPages(f.app,{excludePaths:[f.template.path],excludeFolders:['周记/_临时解密']});
 const runAt=(currentPage:typeof pages[number])=>{
  const r=executeDql(WEEKLY_HISTORY_QUERY,sameWeekPages,{currentPage,deduplicateLinkedTasks:true});
  assert.ok(r.ok&&!r.empty);return flatten(r.result.rows).map(row=>row.task!.text);
 };
 assert.deepEqual(runAt(sameWeekPages.find(p=>p.file===peer)!),['Current','Alpha','Legacy','Earlier'],'include same-week other board; exclude self, completed, future');
 assert.deepEqual(runAt(sameWeekPages.find(p=>p.file===f.current)!),['Peer','Alpha','Legacy','Earlier'],'same-week query is symmetric and excludes current file');
 assert.deepEqual(runAt(sameWeekPages.find(p=>p.file===f.history)!),['Earlier'],'an older board does not include later weeks');
 const futurePage=sameWeekPages.find(p=>p.file===f.future)!;
 const futurePeer={...futurePage,file:{...futurePage.file,path:'周记/__future_peer.md'}};
 const futureResult=executeDql(WEEKLY_HISTORY_QUERY,[...sameWeekPages,futurePeer],{currentPage:futurePage,deduplicateLinkedTasks:true});
 assert.ok(futureResult.ok&&!futureResult.empty);
 assert.ok(!flatten(futureResult.result.rows).some(row=>row.task!.text==='Future'),'calendar boundary excludes other future boards');
 const before=f.reads();await buildPages(f.app,{canRead:()=>false});assert.equal(f.reads(),before,'locked query does not read');
 assert.equal(f.writes(),0);
 console.log('DQL history: indexed fields, legacy cells, configurable WHERE/SORT/LIMIT/GROUP, this context, dedup, year parsing, readonly index passed');
}
void main().catch(error=>{console.error(error);process.exitCode=1;});
