import assert from 'node:assert/strict';
import { TableLayoutStore, reconcileTableLayout, calculateTableWidths, tableColumnDefaults, sanitizeTableLayouts, type TableLayouts } from '../src/table-layout';
import { parse, serialize, generateEmptyWeeklyMarkdown } from '../src/parser';
import { parseTableSectionRows, serializeDenseRows, buildMergedTableGrid, addTableRowAt, insertTableColumnAt, deleteTableRowAt, deleteTableColumnAt } from '../src/table-model';

async function main() {
    const data = parse(generateEmptyWeeklyMarkdown());
    const column = data.columns.find(c => c.sectionType === 'table')!;
    const markdown = serialize(data), content = column.tableContent!;
    let rows = parseTableSectionRows(content);
    let layout = reconcileTableLayout(undefined, content);
    const originalColumn = layout.columns[4]!.id, originalRow = layout.rows[4]!.id;
    layout.columns[4]!.size = 287;
    layout.rows[4]!.size = 123;
    rows = insertTableColumnAt(rows, 3);
    layout = reconcileTableLayout(layout, serializeDenseRows(rows), { axis: 'columns', kind: 'insert', index: 3 });
    assert.equal(layout.columns[5]!.id, originalColumn);
    assert.equal(layout.columns[5]!.size, 287);
    assert.equal(layout.columns[3]!.size, undefined);
    assert.equal(layout.rows[4]!.size, 123);
    rows = addTableRowAt(rows, 2, buildMergedTableGrid(rows));
    layout = reconcileTableLayout(layout, serializeDenseRows(rows), { axis: 'rows', kind: 'insert', index: 3 });
    assert.equal(layout.rows[5]!.id, originalRow);
    assert.equal(layout.rows[5]!.size, 123);
    assert.equal(layout.rows[3]!.size, undefined);
    rows = deleteTableRowAt(rows, 3);
    layout = reconcileTableLayout(layout, serializeDenseRows(rows), { axis: 'rows', kind: 'delete', index: 3 });
    rows = deleteTableColumnAt(rows, 3);
    layout = reconcileTableLayout(layout, serializeDenseRows(rows), { axis: 'columns', kind: 'delete', index: 3 });
    assert.equal(layout.columns[4]!.size, 287);
    assert.equal(layout.rows[4]!.size, 123);
    assert.equal(layout.columns[4]!.id, originalColumn);
    assert.equal(layout.rows[4]!.id, originalRow);

    const external = [['A','B','C'],['role','task','day'],['one','private note',''],['two','',''],['','',''],['','','']];
    let externalLayout = reconcileTableLayout(undefined, serializeDenseRows(external));
    externalLayout.columns[1]!.size = 250;
    externalLayout.rows[2]!.size = 140;
    externalLayout.rows[4]!.size = 80;
    const reordered = [external[0]!,external[1]!,external[3]!,external[2]!,external[4]!,external[5]!];
    externalLayout = reconcileTableLayout(externalLayout, serializeDenseRows(reordered));
    assert.equal(externalLayout.rows[3]!.size, 140, 'unique external row carries its height');
    assert.equal(externalLayout.rows[4]!.size, undefined, 'ambiguous blank rows reset');
    assert.equal(externalLayout.columns[1]!.size, 250, 'unique unchanged heading keeps its width');
    const colReordered = reordered.map(row => [row[2]!, row[0]!, row[1]!]);
    externalLayout = reconcileTableLayout(externalLayout, serializeDenseRows(colReordered));
    assert.equal(externalLayout.columns[2]!.size, 250, 'external column reorder follows unique headings');
    assert.ok(!JSON.stringify(externalLayout).includes('private note'), 'no note text in layout settings');

    const defaults = tableColumnDefaults(content);
    const small = calculateTableWidths(layout, defaults, 300);
    assert.ok(small.reduce((a,b) => a+b, 0) > 300, 'narrow panes scroll instead of crushing columns');
    const wide = calculateTableWidths(layout, defaults, 2000);
    assert.ok(Math.abs(wide.reduce((a,b) => a+b, 0) - 2000) < 0.01);
    assert.equal(wide[4], 287, 'manual width survives available-width changes');
    assert.equal(tableColumnDefaults('| A | B |\n| --- | --- |\n| C | D |').length, 2);
    const shiftedHeaders = parseTableSectionRows(content).map(row => ['', '', ...row]);
    shiftedHeaders.splice(1, 0, Array.from({ length: shiftedHeaders[0]!.length }, () => ''));
    const shiftedDefaults = tableColumnDefaults(serializeDenseRows(shiftedHeaders));
    assert.equal(shiftedDefaults[2]!.role, 'role', 'role column follows its heading after leading columns are inserted');
    assert.equal(shiftedDefaults[3]!.role, 'arrow', 'arrow stays narrow after header rows shift');
    const fixed = structuredClone(layout);
    fixed.columns.forEach(c => c.size = 300);
    assert.deepEqual(calculateTableWidths(fixed, defaults, 2000), fixed.columns.map(() => 300));

    let saved: TableLayouts = Object.create(null), writes = 0;
    const store = new TableLayoutStore(() => saved, async () => { writes++; });
    await store.save('周记/one.md', 'section', layout);
    await store.save('周记/two.md', 'section', externalLayout);
    assert.equal(serialize(data), markdown, 'presentation does not mutate Markdown model');
    saved = sanitizeTableLayouts(JSON.parse(JSON.stringify(saved)));
    assert.equal(store.read('周记/one.md', 'section', content).columns[4]!.size, 287);
    const before = writes;
    await store.save('周记/one.md', 'section', layout);
    assert.equal(writes, before, 'identical layout does not write');
    await store.renamePath('周记', '每周');
    assert.ok(saved['每周/one.md']);
    assert.ok(saved['每周/two.md']);
    assert.equal(saved['周记/one.md'], undefined);
    await store.renameSection('每周/one.md', 'section', 'renamed');
    assert.equal(saved['每周/one.md']!.renamed!.columns[4]!.size, 287);
    assert.equal(store.read('copied.md', 'renamed', content).columns[4]!.size, undefined);
    const protectedLayout = store.read('secret.apexenc', 'secure:opaque', content);
    await store.save('secret.apexenc', 'secure:opaque', protectedLayout);
    assert.equal(writes > 0, true);
    assert.deepEqual(sanitizeTableLayouts({ invalid: { bad: { version: 90 } } }).invalid, Object.create(null));
    let shouldFail = true;
    const retryStore = new TableLayoutStore(() => saved, async () => { if (shouldFail) throw Error('disk unavailable'); });
    await assert.rejects(retryStore.save('retry.md', 'table', layout));
    shouldFail = false;
    await retryStore.save('retry.md', 'table', layout);
    const reconciled = store.read('每周/one.md', 'renamed', serializeDenseRows([['new'],['content']]));
    await store.contentChanged('每周/one.md', 'renamed', '| new |\n| --- |\n| content edited |', 'cells');
    assert.equal(saved['每周/one.md']!.renamed!.columns[0]!.id, reconciled.columns[0]!.id, 'local edit cannot resurrect stale external layout');
    console.log('table layout: stable insert/delete identities, external reconciliation, adaptive widths, independent persistence, reload and rename passed');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
