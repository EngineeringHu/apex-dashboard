import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile,access,rm,symlink,readdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {encryptWeekly} from '../dist/tools/encrypt-weekly.mjs';
import {createRecipient,parseEnvelope,resolveRoot,openAll,decryptAsset} from '../src/secure/format.mjs';
const root=await mkdtemp(path.join(tmpdir(),'apex-offline-'));
const checks=[];
try{
 const inputDir=path.join(root,'输入 有空格 & 中文'),outDir=path.join(root,'密文');
 await mkdir(inputDir);await mkdir(outDir);
 const password='abc',recipient=await createRecipient(password),keyring=path.join(inputDir,'.apex-weekly-keyring.json');
 await writeFile(keyring,JSON.stringify(recipient));
 const picture=Buffer.from([137,80,78,71,13,10,26,10,1,2,3]);await writeFile(path.join(inputDir,'示例 图.png'),picture);
 const md='\uFEFF---\r\ndashboard: true\r\ncolumns:\r\n  - name: 周计划表\r\n    type: table\r\n    height: 642\r\n  - name: 不断更新\r\n    type: todo\r\n---\r\n## 周计划表\r\n| 目标 | 周一 |\r\n| --- | --- |\r\n| SECRET | - [ ] task |\r\n![[示例 图.png|200]]\r\n## 不断更新\r\n### Test\r\n- [ ] SECRET\r\n';
 const input=path.join(inputDir,'第1周-10月4号.md'),output=path.join(outDir,'第1周-10月4号.apexenc');
 await writeFile(input,md);
 const result=await encryptWeekly({input,output,keyring});assert.equal(result.assets,1);
 assert.equal(await readFile(input,'utf8'),md,'Original plaintext retained');
 const text=await readFile(output,'utf8');assert(!text.includes('SECRET'));assert(!text.includes('示例 图'));
 const e=parseEnvelope(text),opened=await openAll(e,await resolveRoot(password,e));assert.equal(opened.markdown,md);
 assert.equal(opened.payloads[1].definition.sectionType,'table');assert.equal(opened.payloads[1].definition.height,642);
 assert.equal(opened.payloads[2].definition.sectionType,'todo');
 const ref=opened.payloads[1].assets[0],asset=JSON.parse(await readFile(path.join(outDir,'_assets',ref.id+'.apexasset'),'utf8'));
 assert(Buffer.from(await decryptAsset(asset,ref)).equals(picture));
 await assert.rejects(()=>resolveRoot('bad-password',e));
 checks.push('exact Chinese/BOM/CRLF roundtrip, 3-character password, wrong password, table/todo layout, encrypted image');
 await assert.rejects(()=>encryptWeekly({input,output,keyring}),/覆盖/);assert.equal(await readFile(output,'utf8'),text);
 checks.push('existing ciphertext never overwritten; original Markdown unchanged');
 const missing=path.join(inputDir,'missing.md');await writeFile(missing,'## Memo\n![[示例 图.png]]\n![[absent.png]]'); const assetsBefore=await readdir(path.join(outDir,'_assets'));
 const failed=path.join(outDir,'failed.apexenc');await assert.rejects(()=>encryptWeekly({input:missing,output:failed,keyring}),/未找到/);await assert.rejects(()=>access(failed));assert.deepEqual(await readdir(path.join(outDir,'_assets')),assetsBefore,'Failure removes only newly written ciphertext assets');
 checks.push('missing attachment fails before publishing ciphertext');
 const second=path.join(outDir,'第二份.apexenc');
 const child=spawnSync(process.execPath,[path.resolve('dist/tools/encrypt-weekly.mjs'),input,'--output',second,'--keyring',keyring],{encoding:'utf8'});
 assert.equal(child.status,0,child.stderr);assert(child.stdout.includes('原 .md'));
 const secondEnvelope=parseEnvelope(await readFile(second,'utf8'));assert.equal((await openAll(secondEnvelope,await resolveRoot(password,secondEnvelope))).markdown,md);
 checks.push('real CLI encrypts with unified recipient without password input');
 await writeFile(path.join(inputDir,'.apex-weekly-mode-change.json'),'{}');
 await assert.rejects(()=>encryptWeekly({input,output:path.join(outDir,'pending.apexenc'),keyring}),/未完成/);
 checks.push('pending vault conversion blocks independent encryption');
 console.log(JSON.stringify({passed:true,checks}));
}finally{await rm(root,{recursive:true,force:true});}
